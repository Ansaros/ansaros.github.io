// ===== ТЕКУЩИЙ ЯЗЫК ДЛЯ СТРАНИЦЫ ЦЕН =====
let currentLanguage_price = localStorage.getItem("language") || "ru"

// ===== СИСТЕМА ПЕРЕВОДОВ ДЛЯ СТРАНИЦЫ ЦЕН =====
function translatePricePage() {
  const elements = document.querySelectorAll("[data-translate]")
  elements.forEach((element) => {
    const key = element.getAttribute("data-translate")
    if (translations_price[currentLanguage_price] && translations_price[currentLanguage_price][key]) {
      // For elements with HTML content, use innerHTML
      if (
        key.includes("home_whitening_note") ||
        key.includes("discoloration_desc") ||
        key.includes("suitable_for_cautious") ||
        key.includes("procedure_duration_note") ||
        key.includes("implant_crown_desc") ||
        key.includes("impression_desc") ||
        key.includes("zirconia_crown_desc") ||
        key.includes("emax_crown_desc") ||
        key.includes("emax_veneer_desc") ||
        key.includes("emax_inlay_desc") ||
        key.includes("biomim_desc") ||
        key.includes("partial_braces_desc") ||
        key.includes("ao_empower_desc") ||
        key.includes("ao_minimaster_desc") ||
        key.includes("ligature_fixation")
      ) {
        element.innerHTML = translations_price[currentLanguage_price][key]
      } else {
        element.textContent = translations_price[currentLanguage_price][key]
      }
    }
  })

  // Update page title
  const titles = {
    ru: "Цены - Nelly dental clinic",
    kz: "Бағалар - Nelly dental clinic",
    en: "Prices - Nelly dental clinic",
  }
  document.title = titles[currentLanguage_price] || titles.ru

  // Update lang attribute
  document.documentElement.lang = currentLanguage_price
}

function switchLanguagePrice(lang) {
  currentLanguage_price = lang
  localStorage.setItem("language", lang)

  // Update active language buttons
  document.querySelectorAll(".lang-btn, .mobile-lang-btn").forEach((btn) => {
    btn.classList.remove("active")
  })
  document.querySelectorAll(`[data-lang="${lang}"]`).forEach((btn) => {
    btn.classList.add("active")
  })

  translatePricePage()
}

// ===== ИНИЦИАЛИЗАЦИЯ ЯЗЫКОВЫХ ПЕРЕКЛЮЧАТЕЛЕЙ ДЛЯ СТРАНИЦЫ ЦЕН =====
function initLanguageSwitchersPrice() {
  // Desktop language buttons
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.getAttribute("data-lang")
      switchLanguagePrice(lang)
    })
  })

  // Mobile language buttons
  document.querySelectorAll(".mobile-lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.getAttribute("data-lang")
      switchLanguagePrice(lang)
    })
  })

  // Set active language on load
  document.querySelectorAll(`[data-lang="${currentLanguage_price}"]`).forEach((btn) => {
    btn.classList.add("active")
  })
}

// ===== ИНИЦИАЛИЗАЦИЯ ДЛЯ СТРАНИЦЫ ЦЕН =====
document.addEventListener("DOMContentLoaded", () => {
  // Initialize translations
  translatePricePage()

  // Initialize language switchers
  initLanguageSwitchersPrice()
})
