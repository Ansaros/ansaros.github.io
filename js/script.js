function initBeforeAfterSliders() {
  const sliders = document.querySelectorAll(".before-after-slider, .before-after-slider-card")

  sliders.forEach((slider) => {
    const handle = slider.querySelector(".slider-handle")
    const beforeImg = slider.querySelector(".before-img")
    const sliderLine = slider.querySelector(".slider-line") // The hidden range input

    if (!handle || !beforeImg || !sliderLine) {
      console.warn("Missing elements for slider:", { handle, beforeImg, sliderLine })
      return
    }

    const updateSliderPosition = (value) => {
      const position = Math.max(0, Math.min(1, Number.parseFloat(value)))
      beforeImg.style.clipPath = `polygon(0 0, ${position * 100}% 0, ${position * 100}% 100%, 0 100%)`
      handle.style.left = `${position * 100}%`
      sliderLine.value = position // Keep the hidden input's value in sync
    }

    let isDragging = false

    // Mouse events for dragging the handle
    handle.addEventListener("mousedown", (e) => {
      isDragging = true
      slider.classList.add("dragging") // Optional: add a class for styling while dragging
      e.preventDefault() // Prevent default browser drag behavior (e.g., image dragging)
    })

    document.addEventListener("mousemove", (e) => {
      if (!isDragging) return

      const rect = slider.getBoundingClientRect()
      const mouseX = e.clientX - rect.left
      let newPosition = mouseX / rect.width
      newPosition = Math.max(0, Math.min(1, newPosition)) // Clamp between 0 and 1

      updateSliderPosition(newPosition)
    })

    document.addEventListener("mouseup", () => {
      if (isDragging) {
        isDragging = false
        slider.classList.remove("dragging")
      }
    })

    // Touch events for dragging the handle (for mobile)
    handle.addEventListener(
      "touchstart",
      (e) => {
        isDragging = true
        slider.classList.add("dragging")
        e.preventDefault() // Prevent scrolling while dragging
      },
      { passive: false },
    ) // Use passive: false to allow preventDefault

    document.addEventListener(
      "touchmove",
      (e) => {
        if (!isDragging || !e.touches[0]) return

        const rect = slider.getBoundingClientRect()
        const touchX = e.touches[0].clientX - rect.left
        let newPosition = touchX / rect.width
        newPosition = Math.max(0, Math.min(1, newPosition))

        updateSliderPosition(newPosition)
      },
      { passive: false },
    )

    document.addEventListener("touchend", () => {
      if (isDragging) {
        isDragging = false
        slider.classList.remove("dragging")
      }
    })

    // Click anywhere on the slider to jump the handle (still useful)
    slider.addEventListener("click", (e) => {
      // Only react to clicks if not directly on the handle or during a drag
      if (e.target !== handle && !handle.contains(e.target) && !isDragging) {
        const rect = slider.getBoundingClientRect()
        const clickX = e.clientX - rect.left
        const newPosition = clickX / rect.width
        updateSliderPosition(newPosition)
      }
    })

    // Initialize slider position
    updateSliderPosition(0.5) // Use updateSliderPosition to set initial state
  })
}

