// ===== COUNTER ANIMATION =====
function initCounterAnimation() {
  const counters = document.querySelectorAll(
    ".stat-beautiful[data-count], .stat-media, .stat-card-beautiful, .stat-doctors",
  )

  const animateCounter = (counter) => {
    const target = Number.parseInt(counter.dataset.count || counter.querySelector("[data-count]")?.dataset.count)
    if (isNaN(target)) return // Ensure target is a number

    const numberElement = counter.querySelector(
      ".stat-number, .stat-number-media, .stat-number-big, .stat-number-doctors",
    )
    if (!numberElement) return

    const isPercentage = numberElement.textContent.includes("%")
    const isThousands = target >= 1000
    const isDoctorsStat = counter.classList.contains("stat-doctors")

    let current = 0
    const duration = 2000 // 2 seconds
    const step = target / (duration / 16) // ~60 FPS

    const timer = setInterval(() => {
      current += step
      if (current >= target) {
        current = target
        clearInterval(timer)
      }

      const displayValue = Math.floor(current)

      if (isPercentage) {
        numberElement.textContent = displayValue + "%"
      } else if (isThousands && displayValue >= 1000) {
        numberElement.textContent = (displayValue / 1000).toFixed(1) + "K+"
      } else if (isDoctorsStat) {
        numberElement.textContent = displayValue + (target > 10 ? "+" : "")
      } else {
        numberElement.textContent = displayValue + "+"
      }
    }, 16)
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          animateCounter(entry.target)
          observer.unobserve(entry.target)
        }
      })
    },
    { threshold: 0.5 },
  )

  counters.forEach((counter) => observer.observe(counter))
}

// ===== BEFORE/AFTER SLIDER FUNCTIONALITY (for cases page and cards) =====
function initBeforeAfterSliders() {
  const sliders = document.querySelectorAll(".before-after-slider, .before-after-slider-card")

  sliders.forEach((slider) => {
    const handle = slider.querySelector(".slider-handle")
    const beforeImg = slider.querySelector(".before img") // Target the img inside .before
    const sliderLine = slider.querySelector(".slider-line") // The range input

    if (!handle || !beforeImg || !sliderLine) return

    const updateSliderPosition = (value) => {
      // Ensure value is between 0 and 1
      const position = Math.max(0, Math.min(1, Number.parseFloat(value)))

      // Update clip-path for the 'before' image
      beforeImg.style.clipPath = `polygon(0 0, ${position * 100}% 0, ${position * 100}% 100%, 0 100%)`

      // Update handle position
      handle.style.left = `${position * 100}%`
    }

    // Event listener for the range input
    sliderLine.addEventListener("input", (e) => {
      updateSliderPosition(e.target.value)
    })

    // Event listener for clicks on the slider container (to jump to position)
    slider.addEventListener("click", (e) => {
      // If the click is not directly on the handle or sliderLine, calculate position
      if (e.target !== handle && e.target !== sliderLine) {
        const rect = slider.getBoundingClientRect()
        const clickX = e.clientX - rect.left
        const newPosition = clickX / rect.width
        sliderLine.value = newPosition // Update the range input's value
        updateSliderPosition(newPosition)
      }
    })

    // Initialize slider to 50%
    sliderLine.value = 0.5
    updateSliderPosition(0.5)
  })
}

