// ===== GLOBAL TRANSLATION SYSTEM =====
function translatePage() {
  const elements = document.querySelectorAll("[data-translate]")
  elements.forEach((element) => {
    const key = element.getAttribute("data-translate")
    if (translations[currentLanguage] && translations[currentLanguage][key]) {
      // For elements with HTML content (like descriptions or story texts), use innerHTML
      if (key.includes("description") || key.includes("text")) {
        element.innerHTML = translations[currentLanguage][key]
      } else {
        element.textContent = translations[currentLanguage][key]
      }
    }
  })

  // Update page title based on current path
  const path = window.location.pathname
  let pageTitleKey
  if (path.includes("cases.html")) {
    pageTitleKey = "cases_title"
  } else if (path.includes("contacts.html")) {
    pageTitleKey = "contacts_title"
  } else {
    pageTitleKey = "nav_home" // Default title for home or other pages
  }

  document.title = translations[currentLanguage][pageTitleKey] || "Nelly dental clinic"

  // Update lang attribute
  document.documentElement.lang = currentLanguage

  // Update data-text attributes for animated titles (e.g., on cases page)
  const titleWords = document.querySelectorAll(".title-word[data-text]")
  titleWords.forEach((word) => {
    const key = word.getAttribute("data-translate")
    if (key && translations[currentLanguage] && translations[currentLanguage][key]) {
      word.setAttribute("data-text", translations[currentLanguage][key])
    }
  })
}

function switchLanguage(lang) {
  currentLanguage = lang
  localStorage.setItem("language", lang)

  // Update active language buttons globally
  document.querySelectorAll(".lang-btn, .mobile-lang-btn").forEach((btn) => {
    btn.classList.remove("active")
  })
  document.querySelectorAll(`[data-lang="${lang}"]`).forEach((btn) => {
    btn.classList.add("active")
  })

  translatePage() // Re-translate the entire page
}

// ===== MOBILE MENU =====
function initMobileMenu() {
  const burger = document.getElementById("burger")
  const mobileNav = document.getElementById("mobileNav")
  const menuOverlay = document.getElementById("menuOverlay")
  const closeMenu = document.getElementById("closeMenu")
  const body = document.body

  if (burger && mobileNav && menuOverlay && closeMenu) {
    // Open menu
    burger.addEventListener("click", () => {
      burger.classList.add("active")
      mobileNav.classList.add("open")
      menuOverlay.classList.add("active")
      body.style.overflow = "hidden"
      const firstMenuItem = mobileNav.querySelector("a")
      if (firstMenuItem) {
        setTimeout(() => firstMenuItem.focus(), 300)
      }
    })

    // Close menu
    function closeMobileMenu() {
      burger.classList.remove("active")
      mobileNav.classList.remove("open")
      menuOverlay.classList.remove("active")
      body.style.overflow = ""
      burger.focus() // Return focus to burger button
    }

    closeMenu.addEventListener("click", closeMobileMenu)
    menuOverlay.addEventListener("click", closeMobileMenu)

    // Close when clicking on a link
    const mobileLinks = mobileNav.querySelectorAll("a")
    mobileLinks.forEach((link) => {
      link.addEventListener("click", closeMobileMenu)
    })

    // Close menu with Escape key
    document.addEventListener("keydown", (e) => {
      if (e.key === "Escape" && mobileNav.classList.contains("open")) {
        closeMobileMenu()
      }
    })

    // Touch gestures for mobile menu
    let touchStartX = 0
    let touchEndX = 0

    mobileNav.addEventListener("touchstart", (e) => {
      touchStartX = e.changedTouches[0].screenX
    })

    mobileNav.addEventListener("touchend", (e) => {
      touchEndX = e.changedTouches[0].screenX
      const swipeThreshold = 100
      const swipeDistance = touchEndX - touchStartX
      if (swipeDistance > swipeThreshold) {
        // Swipe right to close menu
        closeMobileMenu()
      }
    })

    // Focus trap for mobile menu accessibility
    function trapFocus(element) {
      const focusableElements = element.querySelectorAll(
        'a[href], button, textarea, input[type="text"], input[type="radio"], input[type="checkbox"], select',
      )
      const firstFocusableElement = focusableElements[0]
      const lastFocusableElement = focusableElements[focusableElements.length - 1]

      element.addEventListener("keydown", (e) => {
        if (e.key === "Tab") {
          if (e.shiftKey) {
            if (document.activeElement === firstFocusableElement) {
              lastFocusableElement.focus()
              e.preventDefault()
            }
          } else {
            if (document.activeElement === lastFocusableElement) {
              firstFocusableElement.focus()
              e.preventDefault()
            }
          }
        }
      })
    }
    trapFocus(mobileNav)
  }
}

