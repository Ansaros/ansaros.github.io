// ===== CURRENT LANGUAGE =====
let currentLanguage_main = localStorage.getItem("language") || "ru"

// ===== TRANSLATION SYSTEM =====
function translateMainPage() {
  const elements = document.querySelectorAll("[data-translate]")
  elements.forEach((element) => {
    const key = element.getAttribute("data-translate")
    if (translations_main[currentLanguage_main] && translations_main[currentLanguage_main][key]) {
      // For elements with HTML content use innerHTML
      if (key.includes("mission_text") || key.includes("testimonial_")) {
        element.innerHTML = translations_main[currentLanguage_main][key]
      } else {
        element.textContent = translations_main[currentLanguage_main][key]
      }
    }
  })

  // Update page title
  const titles = {
    ru: "Nelly dental clinic — Стоматология 5 звезд",
    kz: "Nelly dental clinic — 5 жұлдызды стоматология",
    en: "Nelly dental clinic — 5-star dentistry",
  }
  document.title = titles[currentLanguage_main] || titles.ru

  // Update lang attribute
  document.documentElement.lang = currentLanguage_main
}

function switchMainLanguage(lang) {
  currentLanguage_main = lang
  localStorage.setItem("language", lang)

  // Update active language buttons
  document.querySelectorAll(".lang-btn, .mobile-lang-btn").forEach((btn) => {
    btn.classList.remove("active")
  })
  document.querySelectorAll(`[data-lang="${lang}"]`).forEach((btn) => {
    btn.classList.add("active")
  })

  translateMainPage()
}

// ===== INITIALIZE LANGUAGE SWITCHERS =====
function initMainLanguageSwitchers() {
  // Desktop language buttons
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.getAttribute("data-lang")
      switchMainLanguage(lang)
    })
  })

  // Mobile language buttons
  document.querySelectorAll(".mobile-lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.getAttribute("data-lang")
      switchMainLanguage(lang)
    })
  })

  // Set active language on load
  document.querySelectorAll(`[data-lang="${currentLanguage_main}"]`).forEach((btn) => {
    btn.classList.add("active")
  })
}

// ===== INITIALIZATION =====
document.addEventListener("DOMContentLoaded", () => {
  // Initialize translations
  translateMainPage()

  // Initialize language switchers
  initMainLanguageSwitchers()
})
